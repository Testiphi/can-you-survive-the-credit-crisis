// ---------------------------------------------------------------- 情境提示

export interface Hint {
  level: 'info' | 'warn' | 'danger';
  text: string;
}

/**
 * 生成当前情境下的提示。
 *
 * 低难度给更多、更直白的提示——因为 D0 玩家看到的指标本来就少，
 * 需要有人告诉他「现在该看什么」。
 */
export function buildHints(engine: GameEngine): Hint[] {
  const hints: Hint[] = [];
  const d = engine.config.difficulty as Difficulty;
  const m = engine.state.macro;
  const p = engine.state.player;
  const beginner = d <= 1;

  // ---- 危险类，任何难度都优先显示 ----
  if (p.bankrupt) {
    return [
      {
        level: 'danger',
        text:
          '你已经爆仓了。这一局结束。\n\n' +
          '回头看看：让你出局的往往不是判断错了方向，而是**在正确的方向上没能活到明天**。',
      },
    ];
  }

  if (p.marginCall) {
    hints.push({
      level: 'danger',
      text:
        '⚠ 收到追加保证金通知：你的权益已低于维持保证金要求。\n\n' +
        '补钱、主动减仓，或者等着被强制平仓。强平的成交价带 **2 倍惩罚性滑点**——' +
        '真实世界的强平总是发生在最糟的价格上。',
    });
  }

  const leverage =
    p.equity > 0
      ? [...p.positions.values()].reduce((a, pos) => a + Math.abs(pos.quantity) * (engine.state.prices.get(pos.instrumentId) ?? 0), 0) /
        p.equity
      : 0;

  if (!p.marginCall && leverage > 3) {
    hints.push({
      level: 'warn',
      text: `你的杠杆是 ${leverage.toFixed(1)}×。压力上升时，借钱给你的人会先跑——而你必须跟着卖。`,
    });
  }

  if (m.systemicStress > 0.6 && engine.state.regulator.level < 2) {
    hints.push({
      level: 'warn',
      text: `系统性压力 ${(m.systemicStress * 100).toFixed(0)}%，已经到 2008 年 9 月那个级别。流动性只剩 ${(m.liquidity * 100).toFixed(0)}%——现在下大单会付出很高的滑点，甚至只成交一部分。`,
    });
  }

  // ---- 教学类，低难度给更多 ----
  if (beginner) {
    const t = engine.state.turnIndex;

    if (t <= 2) {
      hints.push({
        level: 'info',
        text:
          '怎么玩：看完新闻，用左边的按钮做多 / 做空 / 清仓，然后推进时间。\n\n' +
          '**先把鼠标停在任意按钮或指标名上**，会弹出它是干什么的。',
      });
      hints.push({
        level: 'info',
        text:
          '这个游戏里，**新闻往往比 K 线更早告诉你发生了什么**。\n\n' +
          '因为债市和融资市场的反应总是领先于股价——K 线是结果，新闻是原因。',
      });
    }

    if (t > 2 && t <= 30 && p.positions.size === 0) {
      hints.push({
        level: 'info',
        text: '你还空仓。空仓也是一种选择——但在这个游戏里，**空仓保本只能拿到中等成绩**。想拿高分，你得在某个时点做出判断并承担后果。',
      });
    }

    // 指标教学：只在指标可见时才提
    if (d >= 1) {
      if (m.creditSpread > 450 && m.creditSpread < 900) {
        hints.push({
          level: 'info',
          text: `信用利差已经涨到 ${m.creditSpread.toFixed(0)}bp（平时约 300bp）。\n\n这是**最早的预警信号**：债市比股市更早意识到企业可能还不上钱。现在股价可能还没跌。`,
        });
      }
      if (m.vix > 35) {
        hints.push({
          level: 'info',
          text: `VIX 到了 ${m.vix.toFixed(0)}。市场预期未来波动会很大。\n\n注意：**VIX 高的时候买保护很贵**——保险在危机里是最贵的商品。`,
        });
      }
      if (m.tedSpread > 2.0) {
        hints.push({
          level: 'info',
          text: `TED 利差 ${m.tedSpread.toFixed(2)}%——银行之间开始不信任彼此了。\n\n这是「融资断裂」最直接的读数：不是没人有钱，是没人敢借。`,
        });
      }
    }
  }

  // ---- D2+ 的机制提示 ----
  if (d >= 2) {
    if (m.repoHaircut > 0.3 && p.repoCapacity > 0) {
      hints.push({
        level: 'warn',
        text: `回购折扣率 ${(m.repoHaircut * 100).toFixed(0)}%，你的融资容量只剩 $${Math.round(p.repoCapacity).toLocaleString('en-US')}。\n\n折扣率每往上跳一档，你就得卖出一批资产来补缺口——而所有人同时卖，价格就崩了。`,
      });
    }
    if (engine.state.regulator.level >= 3) {
      hints.push({
        level: 'warn',
        text: `监管关注度 L${engine.state.regulator.level}：你的保证金要求已上调，部分做空通道被关闭。\n\n**监管不是随机惩罚——是你自己的仓位规模招来的。**`,
      });
    }
  }

  return hints.slice(0, 3);
}
